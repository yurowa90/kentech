    const game = MAP[gameId] || null, cards = SCI[gameId] || {};
    let type = typeOf(q);
    const byKey = game && key && Object.hasOwn(game.keys, key) ? game.keys[key] : null;
    const tag = q && q.tag ? q.tag : "";
    const byTag = !byKey && game ? (game.tags[tag] || Object.entries(game.tags).find(([k]) => tag.startsWith(k))?.[1] || null) : null;
    const hit = byKey || byTag;
    const forced = hit && hit.type ? TYPES.find((t) => t.id === hit.type) : null;
    if (forced) type = forced;
    const ids = hit && hit.sci ? hit.sci : game ? game.fallback : [];
    return {
      type: type.id,
      el: type.el,
      pick: hit && hit.pick ? hit.pick : type.pick,
      pts: type.pts.concat(hit && hit.pts ? hit.pts : []),
      short: type.short,
      own: hit && hit.pts ? hit.pts[0] : "",
      sci: ids.map((id) => cards[id]).filter(Boolean),
      exact: !!hit,
    };
